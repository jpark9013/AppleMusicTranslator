import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
// CI stamps release builds through PLUGIN_VERSION; otherwise package.json wins.
const version = process.env.PLUGIN_VERSION || JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`Invalid plugin version: ${version}`)
const core = readFileSync(join(root, "lib/core.mjs"), "utf8").replace(/^export /gm, "")
const host = readFileSync(join(root, "src/cider-host.js"), "utf8")
const banner = "/* Generated by cider-plugin/scripts/bundle.mjs. Edit lib/core.mjs and src/cider-host.js. */\n"
mkdirSync(join(root, "dist"), { recursive: true })
writeFileSync(join(root, "dist/plugin.js"), `${banner}const PLUGIN_VERSION = "${version}"\n${core}\n${host}\n`)
writeFileSync(
  join(root, "dist/plugin.yml"),
  `name: Lyrics Translator
identifier: com.jpark9013.apple-music-translator
description: Translate lyrics with DeepSeek and show them under each line in Cider.
author: jpark9013
version: ${version}
entry: plugin.js
`
)
writeFileSync(
  join(root, "dist/plugin.json"),
  `${JSON.stringify(
    {
      name: "Lyrics Translator",
      identifier: "com.jpark9013.apple-music-translator",
      description: "Translate lyrics with DeepSeek and show them under each line in Cider.",
      author: "jpark9013",
      version,
      entry: { "plugin.js": { type: "main" } },
    },
    null,
    2
  )}\n`
)
console.log("Wrote cider-plugin/dist/plugin.js")
