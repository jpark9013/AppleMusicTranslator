import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const core = readFileSync(join(root, "lib/core.mjs"), "utf8").replace(/^export /gm, "")
const host = readFileSync(join(root, "src/cider-host.js"), "utf8")
const banner = "/* Generated by cider-plugin/scripts/bundle.mjs. Edit lib/core.mjs and src/cider-host.js. */\n"
mkdirSync(join(root, "dist"), { recursive: true })
writeFileSync(join(root, "dist/plugin.js"), `${banner}'use strict';\n${core}\n${host}\n`)
writeFileSync(
  join(root, "dist/plugin.yml"),
  `name: Lyrics Translator
identifier: com.jpark9013.apple-music-translator
description: Translate lyrics with Claude and show them under each line in Cider.
author: jpark9013
version: 0.1.0
entry: plugin.js
`
)
writeFileSync(
  join(root, "dist/plugin.json"),
  `${JSON.stringify(
    {
      name: "Lyrics Translator",
      identifier: "com.jpark9013.apple-music-translator",
      description: "Translate lyrics with Claude and show them under each line in Cider.",
      author: "jpark9013",
      version: "0.1.0",
      entry: { "plugin.js": { type: "main" } },
    },
    null,
    2
  )}\n`
)
console.log("Wrote cider-plugin/dist/plugin.js")
